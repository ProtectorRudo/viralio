import {chromium} from '@playwright/test';
const url=process.env.HIJOS_URL||'http://127.0.0.1:3999/tehiceesto/experiencias/hijos';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const assert=(condition,message)=>{if(!condition)throw new Error(message)};
const scene=()=>page.locator('.thi-theme-hijos').getAttribute('data-scene');
const advance=async()=>{const b=page.locator('[data-action="next"]');assert(await b.count(), 'missing next button');await b.evaluate(x=>x.click());await page.waitForTimeout(350)};
try{
await page.goto(url,{waitUntil:'domcontentloaded',timeout:60000});
await page.waitForTimeout(1000);
assert(await scene()==='intro','intro missing');
console.log('HIJOS INTRO:',await page.locator('.thi-scene h1').first().innerText());
await advance();assert(await scene()==='timeline','timeline missing');
assert(await page.locator('.thi-child-timeline-photo img').count()===4,'four photo chapters missing');
console.log('HIJOS TIMELINE: 4 cinematic photo chapters visible');
await advance();assert(await scene()==='memories','memories missing');
assert(await page.locator('.thi-memory').count()>=3,'memories cards missing');
await advance();assert(await scene()==='voices','voices missing');
await page.locator('[data-action="demo-voice"]').first().evaluate(x=>x.click());
await advance();assert(await scene()==='light','light scene missing');
const quest=page.locator('[data-action="child-light-quest"]');
assert(await quest.count()===1,'interactive light quest missing');
const box=await quest.boundingBox();assert(box,'missing quest bounds');
await page.mouse.click(box.x+box.width*.5,box.y+box.height*.5);
await page.waitForTimeout(100);
assert(await page.locator('[data-action="child-light-quest"].is-revealed').count()===0,'light reveals on a single tap');
const spots=[[.21,.28],[.78,.43],[.5,.78],[.24,.28],[.74,.43],[.52,.78]];
await page.mouse.move(box.x+box.width*.16,box.y+box.height*.21);
await page.mouse.down();
for(const [x,y] of spots)await page.mouse.move(box.x+box.width*x,box.y+box.height*y,{steps:14});
await page.mouse.up();
await page.waitForTimeout(450);
const light=await page.locator('[data-action="child-light-quest"]').evaluate(el=>({found:el.getAttribute('data-found'),revealed:el.classList.contains('is-revealed')}));
console.log('HIJOS LIGHT:',JSON.stringify(light));
assert(light.found==='3'&&light.revealed,'flashlight must reveal only after exploring all three hotspots');
await advance();assert(await scene()==='stars','star scene missing');
assert(await page.locator('.thi-child-meteor-shower i').count()>=20,'falling stars missing');
for(let i=0;i<5;i++){await page.locator('.thi-child-star-node.active').evaluate(x=>x.click());await page.waitForTimeout(80)}
assert(await page.locator('.thi-child-heart-sky.complete').count()===1,'heart not completed');
const shower=await page.locator('.thi-child-meteor-shower i').first().evaluate(el=>getComputedStyle(el).animationName);
console.log('HIJOS HEART:',JSON.stringify({shower,stars:await page.locator('.thi-child-star-node.revealed').count()}));
assert(shower.includes('thiChildFallingStar'),'meteor animation missing');
await advance();assert(await scene()==='capsule','chest scene missing');
assert(await page.locator('.thi-child-treasure.open').count()===0,'chest opens before touch');
await page.locator('[data-action="open-capsule"]').evaluate(x=>x.click());
await page.waitForTimeout(1250);
assert(await page.locator('.thi-child-treasure.open').count()===1,'chest did not open');
const letter=await page.locator('.thi-child-treasure-letter').evaluate(el=>({opacity:getComputedStyle(el).opacity,text:el.textContent?.slice(0,110)}));
console.log('HIJOS CHEST:',JSON.stringify(letter));
assert(Number(letter.opacity)>.95,'letter did not rise out of chest');
assert(letter.text?.includes('Podés empezar de nuevo'),'personal message absent from chest');
const sizes=await page.evaluate(()=>({body:document.documentElement.scrollWidth,viewport:window.innerWidth}));
console.log('HIJOS MOBILE WIDTH:',JSON.stringify(sizes));
assert(sizes.body<=sizes.viewport+2,'horizontal page overflow');
assert(errors.length===0,'JavaScript errors: '+errors.join('; '));
console.log('SUCCESS: Hijos model light exploration, star rain and interactive chest pass mobile browser.');
}finally{await browser.close()}
