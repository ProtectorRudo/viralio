import { chromium } from "@playwright/test";
import {mkdirSync} from "node:fs";
const url="https://tehiceesto.com/demo/secreto";
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,hasTouch:true,isMobile:true});
const errors=[];
page.on("pageerror",e=>errors.push("pageerror: "+e.message));
page.on("console",m=>{if(m.type()==="error")errors.push("console: "+m.text());});
const progress=async (expected)=>{
 const value=await page.locator(".secret-content .secret-scene").count();
 if(value!==1)throw new Error("Expected one active scene, got "+value);
 const title=await page.locator(".secret-kicker").textContent();
 console.log("Scene "+expected+" → "+title);
};
try{
 const response=await page.goto(url,{waitUntil:"domcontentloaded",timeout:40000});
 console.log("Visited "+url+" HTTP "+response.status());
 await page.locator(".secret-invitation h1").waitFor({timeout:50000});
 await progress(0);
 mkdirSync("secret-cdn-qa",{recursive:true});
 await page.screenshot({path:"secret-cdn-qa/01-envelope-mobile.png",fullPage:true});
 await page.locator(".secret-envelope").click();
 await page.locator(".secret-bottom-nav button").click();
 await page.locator(".secret-threshold").waitFor();
 await progress(1);
 await page.locator(".secret-doorframe").click();
 await page.locator(".secret-bottom-nav button").click();
 await page.locator(".secret-gallery").waitFor();
 await progress(2);
 for(let i=0;i<3;i++)await page.locator(".secret-gallery-frame").nth(i).click();
 await page.locator(".secret-bottom-nav button").click();
 await page.locator(".secret-time").waitFor();
 await progress(3);
 for(let i=0;i<3;i++)await page.locator(".secret-mechanical-btn").click();
 await page.locator(".secret-bottom-nav button").click();
 await page.locator(".secret-recording").waitFor();
 await progress(4);
 await page.locator(".secret-play").click();
 await page.locator(".secret-bottom-nav button").click();
 await page.locator(".secret-clues").waitFor();
 await progress(5);
 for(let i=0;i<3;i++)await page.locator(".secret-glass-orb").nth(i).click();
 await page.locator(".secret-bottom-nav button").click();
 await page.locator(".secret-confession").waitFor();
 await progress(6);
 await page.locator(".secret-folded-letter").click();
 await page.locator(".secret-bottom-nav button").click();
 await page.locator(".secret-passage").waitFor();
 await progress(7);
 await page.locator(".secret-hold").focus();
 await page.keyboard.press("Enter");
 await page.locator(".secret-bottom-nav button").click();
 await page.locator(".secret-revelation").waitFor();
 await progress(8);
 for(let i=0;i<4;i++)await page.locator(".secret-mechanical-btn").click();
 await page.locator(".secret-big-reveal").waitFor();
 await page.screenshot({path:"secret-cdn-qa/09-revelation-mobile.png",fullPage:true});
 await page.locator(".secret-bottom-nav button").click();
 await page.locator(".secret-keepsake").waitFor();
 await progress(9);
 await page.screenshot({path:"secret-cdn-qa/10-keepsake-mobile.png",fullPage:true});
 console.log("Full ten-scene mobile journey PASS");
 console.log("JS browser errors="+JSON.stringify(errors));
 if(errors.some(e=>/Uncaught|ReferenceError|Failed to load module|invalid hook call/i.test(e)))throw Error("Fatal browser errors");
} catch(e){
 await page.screenshot({path:"secret-cdn-qa/failed-mobile.png",fullPage:true}).catch(()=>{});
 console.error("QA FAILED "+e.stack);
 console.error("Errors "+JSON.stringify(errors));
 process.exitCode=1;
} finally { await browser.close(); }
